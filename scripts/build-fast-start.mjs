import {readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
await import('./build-sources.mjs');
let html=await readFile('scripts/game-template.html','utf8');
const game=await readFile('dist/game.js','utf8');
const login=game.slice(game.indexOf('function renderHostLogin()')).match(/\$\('#app'\)\.innerHTML = `([\s\S]*?)`;/)[1].replace('${homeCharacters()}','').replaceAll('<button ','<button disabled ');
let css='';
const matches=[...html.matchAll(/<link rel="stylesheet" href="([^\"]+)">|<style>([\s\S]*?)<\/style>/g)];
for(const match of matches)css+=(match[1]?await readFile('dist'+match[1].split('?')[0],'utf8'):match[2])+'\n';
for(const match of matches)html=html.replace(match[0],'');
html=html.replace('</head>','<link rel="stylesheet" href="/app-v64.css">\n</head>');
html=html.replace('<div id="app"></div>',`<div id="app" data-login-shell>${login}</div>`);
html=html.replace(/^[\t ]+$/gm,'');
await writeFile('dist/app-v64.css',css);
const hash=value=>createHash('sha256').update(value).digest('hex').slice(0,16);
const versions={};
for(const name of (await readdir('dist')).filter(n=>/\.(js|css)$/.test(n)&&n!=='sw.js').sort())versions['/'+name]=hash(await readFile('dist/'+name));
for(const name of (await readdir('dist/assets/role-cards-v3')).filter(n=>n.endsWith('.webp')).sort())versions['/assets/role-cards-v3/'+name]=hash(await readFile('dist/assets/role-cards-v3/'+name));
for(const name of (await readdir('dist/assets/role-cards-kids')).filter(n=>n.endsWith('.webp')).sort())versions['/assets/role-cards-kids/'+name]=hash(await readFile('dist/assets/role-cards-kids/'+name));
versions['/assets/mafia-gold-icon.webp']=hash(await readFile('dist/assets/mafia-gold-icon.webp'));
html=html.replace(/(src|href)="(\/[^"?]+\.(?:js|css))(?:\?[^\"]*)?"/g,(_,attr,url)=>`${attr}="${url}?v=${versions[url]}"`);
const release=hash(JSON.stringify(versions));
html=html.replace('</head>',`<script>window.MAFIA_RELEASE=${JSON.stringify(release)};window.MAFIA_ASSETS=${JSON.stringify(Object.fromEntries(['/admin.js','/qrcode.js','/admin-qr.js'].map(p=>[p,p+'?v='+versions[p]])))};</script>\n</head>`);
const sw=await readFile('dist/sw.js','utf8');
await writeFile('dist/sw.js',sw.replace(/const CACHE = '[^']+';/,`const CACHE = 'mafia-${release}';`));
await writeFile('dist/release.json',JSON.stringify({release,versions},null,2));
await writeFile('dist/game.html',html);await writeFile('dist/index.html',html);
console.log('Built static login and ordered stylesheet bundle');
